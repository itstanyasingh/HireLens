import { AnalysisReport } from '../services/api';

/**
 * Downloads a structured text/markdown report for the analyzed resume
 */
export function downloadAnalysisReport(report: AnalysisReport) {
  const dateStr = new Date(report.analyzedAt || Date.now()).toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric'
  });

  const content = `===================================================================
HIRELENS — RESUME AUDIT & ATS INTELLIGENCE REPORT
===================================================================
File: ${report.fileName}
Analyzed: ${dateStr}
Overall Score: ${report.overallScore}/100

-------------------------------------------------------------------
1. EXECUTIVE SCORE BREAKDOWN
-------------------------------------------------------------------
- Overall Score:           ${report.overallScore}/100
- ATS Compatibility:       ${report.atsScore}%
- Content Quality:         ${report.contentScore}%
- Skills & Tech Stack:     ${report.skillsScore}%
- Recruiter Screen:        ${report.recruiterScore}%
${report.jobDescription ? `- Targeted Job Match:     ${report.jobMatchScore}%\n` : ''}
Scoring Methodology:
Overall = (ATS × 30%) + (Content × 25%) + (Skills × 20%) + (Recruiter × 25%)

-------------------------------------------------------------------
2. ATS ESSENTIALS & PARSEABILITY (${report.categories.ats.passedChecks}/${report.categories.ats.totalChecks} PASSED)
-------------------------------------------------------------------
${report.categories.ats.items.map(item => `[${item.passed ? 'PASS' : 'WARN'}] ${item.name}: ${item.detail}`).join('\n')}

-------------------------------------------------------------------
3. RESUME STRUCTURE AUDIT
-------------------------------------------------------------------
${report.categories.structure.items.map(sec => `[${sec.status.toUpperCase()}] ${sec.name}: ${sec.detail}`).join('\n')}

-------------------------------------------------------------------
4. CONTENT QUALITY & ACHIEVEMENTS
-------------------------------------------------------------------
- Quantifiable Metrics Identified: ${report.categories.content.quantifiedAchievementsCount}
${report.categories.content.weakBullets.length > 0 ? `
Weak Statements Needing Improvement (${report.categories.content.weakBullets.length}):
${report.categories.content.weakBullets.map((b, i) => `
#${i + 1} Original: "${b.original}"
   Issue:    ${b.reason}
   Suggested: "${b.suggestion}"
`).join('\n')}` : '\nNo weak or duty-only statements detected. Excellent achievement phrasing!'}

-------------------------------------------------------------------
5. DETECTED SKILLS & DOMAIN STRENGTH
-------------------------------------------------------------------
Extracted Skills (${report.categories.skills.detectedSkills.length}):
${report.categories.skills.detectedSkills.join(', ')}

Domain Evaluation:
${report.categories.skills.skillStrength.map(s => `- ${s.category}: ${s.level}`).join('\n')}

-------------------------------------------------------------------
6. KEYWORD ALIGNMENT
-------------------------------------------------------------------
- Matched Keywords: ${report.categories.keywords.matchedKeywords.join(', ') || 'None'}
- Missing Keywords: ${report.categories.keywords.missingKeywords.join(', ') || 'None'}

-------------------------------------------------------------------
7. RECRUITER HUMAN SCREEN
-------------------------------------------------------------------
Key Strengths:
${report.categories.recruiter.strengths.map(s => `✓ ${s}`).join('\n')}

Areas for Improvement:
${report.categories.recruiter.improvements.map(i => `! ${i}`).join('\n')}

-------------------------------------------------------------------
8. HIGH-PRIORITY ACTION PLAN
-------------------------------------------------------------------
${report.actionPlan.map((plan, idx) => `
${idx + 1}. [${plan.priority}] ${plan.title}
   Why:    ${plan.reason}
   Action: ${plan.action}
   Sample: ${plan.suggestionSample}
`).join('\n')}

===================================================================
Generated by HireLens Resume Intelligence
https://hirelens.ai
===================================================================
`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `HireLens_Audit_${report.fileName.replace(/\.[^/.]+$/, '')}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Downloads a complete evidence-based Match Lab audit report
 */
export function downloadMatchLabAuditReport(params: {
  fileName?: string;
  audit: any;
  matches: any[];
  qualityInspection?: any;
  skillGaps?: any[];
}) {
  const dateStr = new Date().toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  const { audit, matches, qualityInspection, skillGaps, fileName = 'Candidate_Resume.pdf' } = params;

  const content = `===================================================================
HIRELENS — EXPLAINABLE JOB MATCH & EVIDENCE AUDIT REPORT
===================================================================
File: ${fileName}
Generated: ${dateStr}
Final Match Estimate: ${audit.overallScore ?? 'Unable to calculate'}%
Scoring Reliability: ${audit.isReliable ? 'VERIFIED (Deterministic)' : 'UNRELIABLE / BLOCKED'}

-------------------------------------------------------------------
1. MATHEMATICAL FORMULA & SUBSTITUTION AUDIT
-------------------------------------------------------------------
Formula:
Score = 100 × [ Σ(wᵢ × sᵢ) / Σwᵢ ]

Where:
- wᵢ = Documented weight of requirement i (1 to 5)
- sᵢ = 1.0 (MATCHED), 0.5 (PARTIAL), 0.0 (NOT FOUND)
- Unresolved items (NEEDS REVIEW) excluded from active denominator

Calculation Step:
${audit.intermediateCalculation}

Summary Counts:
- Total Extracted Requirements: ${audit.totalRequirementsCount}
- Assessed Requirements:        ${audit.assessedCount} (${audit.coveragePercentage}% coverage)
- Matched Points Earned:        ${audit.matchedWeight.toFixed(1)} pts (${audit.matchedCount} reqs)
- Partial Points Earned:        ${audit.partialWeight.toFixed(1)} pts (${audit.partialCount} reqs)
- Not Found in Resume:          ${audit.notFoundCount} reqs (0.0 pts)
- Unresolved (Needs Review):    ${audit.needsReviewCount} reqs

-------------------------------------------------------------------
2. REQUIREMENT-BY-REQUIREMENT EVIDENCE TRAIL
-------------------------------------------------------------------
${matches.map((m, idx) => `
[${m.status}] ${idx + 1}. ${m.requirement.name} (Weight ${m.requirement.weight} - ${m.requirement.importanceLevel})
Category:           ${m.requirement.category}
Contribution:       +${m.scoreContribution.toFixed(1)} points
Target Job Excerpt: "${m.requirement.sourceExcerpt}"
Resume Evidence:    ${m.resumeExcerpt ? `"${m.resumeExcerpt}"` : 'None identified in document.'}
Audit Decision:     ${m.explanation}
${m.limitations ? `Limitations:        ${m.limitations}` : ''}
-------------------------------------------------------------------`).join('')}

-------------------------------------------------------------------
3. DOCUMENT DATA QUALITY INSPECTION
-------------------------------------------------------------------
${qualityInspection ? `
- Readiness Score:          ${qualityInspection.readinessScore}/100 (${qualityInspection.overallStatus})
- Substantive Token Count:  ${qualityInspection.tokenCount} words (${qualityInspection.characterCount} chars)
- Detected ATS Sections:    ${qualityInspection.detectedSections.map((s: any) => s.name).join(', ')}
- Missing Sections:         ${qualityInspection.missingSections.length > 0 ? qualityInspection.missingSections.join(', ') : 'None (Full structure)'}
- Contact Details:          Email: ${qualityInspection.contactDetails.email.value || 'Missing'} | Phone: ${qualityInspection.contactDetails.phone.value || 'Missing'}
- Timeline Sanity:          ${qualityInspection.timelineConsistency.hasIssues ? 'Inconsistencies detected in dates' : 'Chronology verified'}
` : 'Not run.'}

-------------------------------------------------------------------
4. SKILL GAPS & PRACTICAL ACTION ROADMAP
-------------------------------------------------------------------
${skillGaps && skillGaps.length > 0 ? skillGaps.map((g: any, i: number) => `
${i + 1}. ${g.skill} [${g.status}] (Weight ${g.requirementWeight})
   Why: ${g.missingEvidenceReason}
   Recommended Topics to Master:
   ${g.learningTopics.map((t: string) => `  - ${t}`).join('\n')}
`).join('\n') : 'No significant skill gaps identified against this job description.'}

-------------------------------------------------------------------
5. METHODOLOGICAL LIMITATIONS & DISCLAIMER
-------------------------------------------------------------------
- This score evaluates textual keyword and qualification coverage between the supplied resume and job posting.
- It does NOT constitute a hiring guarantee, employer promise, or universal ATS score.
- "Not Found" indicates absence of textual evidence in the resume, not necessarily an absence of candidate capability.

===================================================================
Generated by HireLens Match Lab — Zero Hallucination Guarantee
===================================================================
`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `HireLens_MatchLab_Audit_${fileName.replace(/\.[^/.]+$/, '')}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
